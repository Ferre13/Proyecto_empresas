function detectInitialLanguage() {
  try {
    const saved = localStorage.getItem('docuflow_lang');
    if (saved && TRANSLATIONS[saved]) return saved;
    const browserLang = (navigator.language || navigator.userLanguage || 'es').slice(0, 2).toLowerCase();
    if (TRANSLATIONS[browserLang]) return browserLang;
  } catch (e) {}
  return 'es';
}

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(detectInitialLanguage);

  const setLang = async (newLang) => {
    if (!TRANSLATIONS[newLang]) return;
    setLangState(newLang);
    try {
      localStorage.setItem('docuflow_lang', newLang);
      document.documentElement.lang = newLang;
      if (isSupabaseConfigured() && supabase) {
        const { data: { session } } = await supabase.auth.getSession();
        if (session) {
          await supabase.auth.updateUser({ data: { preferred_lang: newLang } });
        }
      }
    } catch (e) {}
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = TRANSLATIONS[lang] || TRANSLATIONS.es;

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, languages: LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);
